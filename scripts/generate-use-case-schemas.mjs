#!/usr/bin/env node
/**
 * Generates JSON Schema for every USE_CASE_REGISTRY entry via Zod v4 toJSONSchema().
 *
 * Run:  pnpm schemas:sync
 * Requires @dbt-tools/core to be built (this script builds it if dist is stale).
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');
const OUTPUT_JSON = resolve(REPO_ROOT, 'packages/core/generated/use-case-schemas.json');

function ensureCoreBuilt() {
  const build = spawnSync('pnpm', ['--filter', '@dbt-tools/core', 'build'], {
    cwd: REPO_ROOT,
    stdio: 'inherit',
  });
  if (build.status !== 0) {
    process.exit(build.status ?? 1);
  }
}

function toJsonSchema(zodSchema) {
  if (typeof zodSchema.toJSONSchema !== 'function') {
    throw new TypeError('Expected a Zod v4 schema with toJSONSchema()');
  }
  return zodSchema.toJSONSchema();
}

async function main() {
  ensureCoreBuilt();

  const usecasesModule = pathToFileURL(resolve(REPO_ROOT, 'packages/core/dist/usecases.js')).href;
  const { USE_CASE_REGISTRY } = await import(usecasesModule);

  const useCases = USE_CASE_REGISTRY.map((entry) => ({
    name: entry.name,
    title: entry.title,
    read: entry.read,
    input: toJsonSchema(entry.input),
    output: toJsonSchema(entry.output),
  }));

  const payload = {
    $comment:
      'AUTO-GENERATED by scripts/generate-use-case-schemas.mjs — do not edit manually. Run `pnpm schemas:sync` after changing use-case Zod contracts.',
    generatedAt: new Date().toISOString(),
    useCases,
  };

  mkdirSync(dirname(OUTPUT_JSON), { recursive: true });
  writeFileSync(OUTPUT_JSON, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`✓ Generated ${OUTPUT_JSON} (${useCases.length} use cases)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
